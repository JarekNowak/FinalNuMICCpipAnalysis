"""mp2pi_detvar_factorisation.py -- the assumption behind the fractional detector term of the two-pion one-bin total:
the change of a detector variation, taken as the ratio variation / variation CV in samples simulated with the earlier
NuMI flux, applies to the nominal prediction made with the current flux,
    N_var(current) ~ N_nominal(current) x N_var(old) / N_CV(old).
The ratio is shown per variation and horn mode for the signal and the background of the signal region and of the
score-band sideband, in bins of the true neutrino energy, without and with the event weight to the current flux
(numi_flux_rw_weight of the reweighted copies). A ratio flat in energy, and the same with and without the weight,
supports the factorisation; the ratios also carry the statistics of the variation samples.

Inputs: /data/uboone/processed/mp2pi_mcscal/xsec-ana-detvar_run4<horn>_<variation>.root (CC1mu2piBDT, MCS-calibrated
classifier inputs) and their copies in detvar_fluxw/.

    python3 scripts/mp2pi_detvar_factorisation.py  ->  report/planning/multipion/mp2pi_detvar_factorisation.{json,md}
"""
import json, os
import numpy as np
import uproot

HERE = os.path.dirname(os.path.abspath(__file__))
OUTDIR = os.path.abspath(os.path.join(HERE, '..', '..', 'report', 'planning', 'multipion'))
D = '/data/uboone/processed/mp2pi_mcscal/'
KNOBS = ['LYdown', 'LYrayl', 'Recomb2', 'SCE', 'WMAngleXZ', 'WMAngleYZ', 'WMX', 'WMYZ']
EB = np.array([0., 1., 2., 3., 5., 100.])
CELLS = [('SR signal', 0, True), ('SR background', 0, False), ('score band signal', 3, True), ('score band background', 3, False)]


def safe(w):
    return np.where(np.isfinite(w) & (w >= 0) & (w <= 30), w, 1.)


def load(path, fluxw):
    br = ['CC1mu2piBDT_evt_region', 'CC1mu2piBDT_MC_Signal', 'CC1mu1piXp_Selected', 'mc_nu_energy', 'tuned_cv_weight',
          'ppfx_cv_weight', 'normalisation_weight'] + (['numi_flux_rw_weight'] if fluxw else [])
    a = uproot.open(path)['stv_tree'].arrays(br, library='np')
    w = safe(a['tuned_cv_weight'] * a['ppfx_cv_weight'] * a['normalisation_weight'])
    if fluxw: w = w * a['numi_flux_rw_weight']
    reg = a['CC1mu2piBDT_evt_region']
    reg = np.where((reg >= 1) & a['CC1mu1piXp_Selected'].astype(bool), -1, reg)     # sidebands leave out the 1pi SR
    return dict(reg=reg, sig=a['CC1mu2piBDT_MC_Signal'].astype(bool), e=a['mc_nu_energy'], w=w)


def counts(X):
    out = {}
    for name, g, s in CELLS:
        m = (X['reg'] == g) & (X['sig'] == s)
        out[name] = (np.histogram(X['e'][m], EB, weights=X['w'][m])[0], np.histogram(X['e'][m], EB, weights=X['w'][m] ** 2)[0],
                     float(X['w'][m].sum()))
    return out


def main():
    res = {}
    L = ['# Detector variations of the two-pion selection: factorisation of the fractional treatment', '',
         'Generated by `scripts/mp2pi_detvar_factorisation.py`. Ratio variation / variation CV (Run 4, MCS-calibrated classifier '
         'inputs) of the selected signal and background, in the signal region and the score-band sideband, per bin of the true '
         'neutrino energy; "all" is the integrated ratio without and with the weight to the current flux. Statistical '
         'uncertainties of the ratios (variation and CV treated as independent, an upper bound) in brackets for the integral.', '',
         '| horn | variation | cell | ' + ' | '.join(f'{EB[i]:g}-{EB[i + 1]:g} GeV' for i in range(len(EB) - 2)) + f' | >{EB[-2]:g} GeV '
         '| all | all, flux-weighted |', '|---|---|---|' + '---|' * (len(EB) - 1) + '---|---|']
    for horn in ('fhc', 'rhc'):
        cv = {fw: counts(load(D + ('detvar_fluxw/' if fw else '') + f'xsec-ana-detvar_run4{horn}_CV.root', fw)) for fw in (False, True)}
        for v in KNOBS:
            var = {fw: counts(load(D + ('detvar_fluxw/' if fw else '') + f'xsec-ana-detvar_run4{horn}_{v}.root', fw)) for fw in (False, True)}
            for name, _, _ in CELLS:
                hv, h2v, tv = var[False][name]; hc, h2c, tc = cv[False][name]
                with np.errstate(divide='ignore', invalid='ignore'):
                    r = hv / hc
                err = (tv / tc) * np.sqrt(h2v.sum() / tv ** 2 + h2c.sum() / tc ** 2) if tv > 0 and tc > 0 else float('nan')
                rf = var[True][name][2] / cv[True][name][2]
                res[f'{horn} {v} {name}'] = dict(by_energy=[float(x) for x in r], all=tv / tc, all_err=err, all_fluxw=rf)
                L.append(f'| {horn.upper()} | {v} | {name} | ' + ' | '.join(f'{x:.2f}' if np.isfinite(x) else '-' for x in r)
                         + f' | {tv / tc:.3f} ({err:.3f}) | {rf:.3f} |')
            print('==', horn, v, flush=True)
    json.dump(res, open(os.path.join(OUTDIR, 'mp2pi_detvar_factorisation.json'), 'w'), indent=1, default=float)
    open(os.path.join(OUTDIR, 'mp2pi_detvar_factorisation.md'), 'w').write('\n'.join(L) + '\n')
    print('\n'.join(L[:12]))


if __name__ == '__main__':
    main()
