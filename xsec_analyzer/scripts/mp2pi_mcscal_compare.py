"""mp2pi_mcscal_compare.py -- the two-pion one-bin total with the MCS-calibrated classifier inputs against the
uncalibrated one (DVfrac, detector variations flux-weighted; without and with the sideband constraint). Uncalibrated:
/data/uboone/processed/mp2pi/unfold/*_dvfrac_fluxw.log (scripts/mp2pi_fluxw_univ.sh); calibrated:
/data/uboone/processed/mp2pi_mcscal/unfold/*_dvfrac_fluxw_mcscal.log (configs *_dvfrac_fluxw_mcscal). Per extraction:
the integrated cross section of the pseudo-data, its closure (over the pseudo-data truth of the closure sidecar) and
the fractional uncertainties of the SYSTDUMP.

    python3 scripts/mp2pi_mcscal_compare.py  ->  report/planning/multipion/mp2pi_mcscal_total.md
"""
import os, re
import uproot

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.abspath(os.path.join(HERE, '..', '..', 'report', 'planning', 'multipion', 'mp2pi_mcscal_total.md'))
RUNS = {'uncalibrated': ('/data/uboone/processed/mp2pi/unfold/', '_dvfrac_fluxw'),
        'calibrated': ('/data/uboone/processed/mp2pi_mcscal/unfold/', '_dvfrac_fluxw_mcscal')}
TERMS = [('total', 'total'), ('detVar_total', 'detector'), ('flux_total', 'flux'), ('xsec_total', 'cross section'),
         ('DataStats', 'data statistics'), ('SimulationStats', 'simulation statistics')]
NAMES = {'fhc5': 'FHC', 'rhcfull': 'RHC', 'comb': 'COMB'}


def read(d, cfg, mode, suf):
    t = open(f'{d}{cfg}{mode}{suf}.log').read()
    v = {k: float(x) for k, x in re.findall(r'^\[SYSTDUMP\] (\S+) ([-\d.e+]+)$', t, re.M)}
    f = uproot.open(f'{d}closure_hists_xsec_mp2pi_{cfg}{mode}{suf}_total.root')
    v['unfolded'] = float(f['h_unfolded_nuwro'].values().sum())
    v['truth'] = float(f['h_fakedata_truth'].values().sum())
    v['tune'] = float(f['h_genie_tune'].values().sum())
    return v


def main():
    R = {(lab, cfg, mode): read(d, cfg, mode, suf) for lab, (d, suf) in RUNS.items()
         for cfg in NAMES for mode in ('', '_constr')}
    L = ['# Two-pion one-bin total with the MCS-calibrated classifier inputs', '',
         'Generated by `scripts/mp2pi_mcscal_compare.py`. CC1mu2piBDT signal region, DVfrac, detector variations '
         'weighted to the new NuMI flux; pseudo-data thrown with the same seeds (the same events) in both. The calibrated '
         'production applies the v1.9 MCS map to the classifier inputs of simulated exiting tracks '
         '(CC1MU1PIXP_MP_MCS_MAP) in every simulated sample, the detector variations included.', '',
         '| configuration | constraint | sigma (pseudo-data), uncal -> cal | closure (unfolded / truth) | truth | '
         + ' | '.join(n + ' [%]' for _, n in TERMS) + ' |', '|---|---|---|---|---|' + '---|' * len(TERMS)]
    for cfg, name in NAMES.items():
        for mode, ml in (('', 'none'), ('_constr', 'sidebands')):
            a, b = R[('uncalibrated', cfg, mode)], R[('calibrated', cfg, mode)]
            cells = [f"{a[k]:.1f} -> {b[k]:.1f}" for k, _ in TERMS]
            L.append(f"| {name} | {ml} | {a['sigma_int']:.4f} -> {b['sigma_int']:.4f} ({b['sigma_int'] / a['sigma_int']:.3f}) | "
                     f"{a['unfolded'] / a['truth']:.3f} -> {b['unfolded'] / b['truth']:.3f} | {a['truth']:.4f} -> {b['truth']:.4f} | "
                     + ' | '.join(cells) + ' |')
    L += ['', 'sigma in 10^-38 cm^2 / Ar; the truth is that of the pseudo-data (the same events in both).']
    open(OUT, 'w').write('\n'.join(L) + '\n')
    print('\n'.join(L))


if __name__ == '__main__':
    main()
