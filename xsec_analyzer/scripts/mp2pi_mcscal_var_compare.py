"""mp2pi_mcscal_var_compare.py -- MCS-calibration term of the two-pion one-bin total, as scripts/mcs_cal_compare.py
for the single-pion results: the pseudo-data calibrated with each of the seven variant maps (slurm/
slurm_mp2pi_mcscal_var.sbatch) extracted against the response calibrated with the nominal map, against the nominal
pseudo-data (configs *_dvfrac_fluxw_mcscal). Four fully correlated terms: model = shrink - nominal; grid = the larger
of coarse - nominal and fine - nominal; production = (old_production - new_production) / 2; beam = (FHC - RHC) / 2.
The term is their quadrature sum, as a fraction of the nominal result and against its total uncertainty. The variant
pseudo-data are the nominal thrown events: a variant moves a few of them in or out of the signal region, and the
second table shows that the shifts lie within the Poisson noise of those events, so the term is an upper estimate.

    python3 scripts/mp2pi_mcscal_var_compare.py [--prod 2f]  ->  report/planning/multipion/mp2pi_mcscal_var[_2f].md
        (--prod 2f: the two-fold production, nominal extractions /data/uboone/processed/mp2pi_2f/unfold/total/)
"""
import math, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
PROD = sys.argv[sys.argv.index('--prod') + 1] if '--prod' in sys.argv else ''
OUT = os.path.abspath(os.path.join(HERE, '..', '..', 'report', 'planning', 'multipion', f'mp2pi_mcscal_var{"_" + PROD if PROD else ""}.md'))
N = f'/data/uboone/processed/mp2pi_{PROD or "mcscal"}/'
NOMLOG = (lambda cfg, mode: f'{N}unfold/total/{cfg}{mode}.log') if PROD else (lambda cfg, mode: f'{N}unfold/{cfg}{mode}_dvfrac_fluxw_mcscal.log')
VARIANTS = ['shrink', 'coarse', 'fine', 'old_production', 'new_production', 'FHC', 'RHC']
NAMES = {'fhc5': 'FHC', 'rhcfull': 'RHC', 'comb': 'COMB'}


def systdump(path):
    t = open(path).read()
    return {k: float(x) for k, x in re.findall(r'^\[SYSTDUMP\] (\S+) ([-\d.e+]+)$', t, re.M)}


def main():
    L = ['# MCS-calibration term of the two-pion one-bin total', '',
         'Generated by `scripts/mp2pi_mcscal_var_compare.py`. Pseudo-data with the classifier inputs calibrated by each '
         'variant map (the same thrown events), extracted against the response calibrated with the nominal map; '
         'shifts of the integrated cross section relative to the nominal pseudo-data result.', '',
         '| configuration | constraint | nominal | ' + ' | '.join(VARIANTS) + ' | model | grid | production | beam | '
         'term | term / total uncertainty |', '|---|---|---|' + '---|' * (len(VARIANTS) + 6)]
    for cfg, name in NAMES.items():
        for mode, ml in (('', 'none'), ('_constr', 'sidebands')):
            nom = systdump(NOMLOG(cfg, mode))
            s0, tot = nom['sigma_int'], nom['total'] / 100.
            v = {}
            for V in VARIANTS:
                p = f'{N}var/{V}/unfold/{cfg}{mode}.log'
                v[V] = systdump(p).get('sigma_int', float('nan')) / s0 - 1 if os.path.exists(p) else float('nan')
            terms = {'model': v['shrink'], 'grid': max(abs(v['coarse']), abs(v['fine'])),
                     'production': (v['old_production'] - v['new_production']) / 2, 'beam': (v['FHC'] - v['RHC']) / 2}
            term = math.sqrt(sum(x * x for x in terms.values()))
            L.append(f'| {name} | {ml} | {s0:.4f} | ' + ' | '.join(f'{v[V]:+.2%}' for V in VARIANTS) + ' | '
                     + ' | '.join(f'{abs(terms[k]):.2%}' for k in ('model', 'grid', 'production', 'beam'))
                     + f' | {term:.2%} | {term / tot:.2f} |')
    L += ['', 'Total uncertainty: the SYSTDUMP total of the nominal calibrated extraction (without the calibration term).']
    # the variant pseudo-data hold the nominal entries in the same order: count, entry by entry, the pseudo-data events
    # that each variant moves into and out of the signal region, and their Poisson noise
    import numpy as np, uproot
    R = 'CC1mu2piBDT_evt_region'
    files = {'FHC': ['fhc_run1', 'fhc_run2', 'fhc_run4', 'fhc_run5'], 'RHC': ['rhc_run1', 'rhc_run2', 'rhc_run3', 'rhc_run4']}
    nom = {f: uproot.open(f'{N}xsec-ana-fakedata_{f}.root')['stv_tree'][R].array(library='np') for m in files for f in files[m]}
    L += ['', '## Pseudo-data events moved by each variant (signal region, against the nominal pseudo-data)', '',
          'The extracted shift follows the change of the pseudo-data signal-region count; its Poisson noise is '
          'sqrt(entering + leaving). Pull = change / noise.', '',
          '| variant | mode | entering | leaving | change | noise | pull | shift of the unconstrained result |',
          '|---|---|---|---|---|---|---|---|']
    for V in VARIANTS:
        for m, cfg in (('FHC', 'fhc5'), ('RHC', 'rhcfull')):
            ni = no = 0
            for f in files[m]:
                v = uproot.open(f'{N}var/{V}/xsec-ana-fakedata_{f}.root')['stv_tree'][R].array(library='np')
                ni += int(((nom[f] != 0) & (v == 0)).sum()); no += int(((nom[f] == 0) & (v != 0)).sum())
            nz = math.sqrt(ni + no)
            sh = systdump(f'{N}var/{V}/unfold/{cfg}.log')['sigma_int'] / systdump(NOMLOG(cfg, ''))['sigma_int'] - 1
            L.append(f'| {V} | {m} | {ni} | {no} | {ni - no:+d} | {nz:.1f} | {(ni - no) / nz if nz else 0:+.1f} | {sh:+.2%} |')
    open(OUT, 'w').write('\n'.join(L) + '\n')
    print('\n'.join(L))


if __name__ == '__main__':
    main()
