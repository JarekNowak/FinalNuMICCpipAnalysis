"""mcs_cal_compare.py -- the MCS-calibrated results (slurm/slurm_mcscal_extract.sbatch) against version 1.8, and the
calibration uncertainty from the variant maps (slurm/slurm_mcscal_var.sbatch).

Calibration covariance per result, fully correlated terms (C = sum of d d^T):
  model       shrink - nominal (parametric map instead of the quantile maps)
  grid        coarse - nominal or fine - nominal, whichever is larger in units of the total covariance
  production  (old production - new production) / 2 (maps from the two halves of the control-region data)
  beam        (FHC - RHC) / 2
Written as /data/uboone/processed/mcscal/nominal_out/<tag>/cov_MCScal.txt, with cov_total_plusMCScal.txt = cov_total + C.

Per result: integral and per-bin ratio calibrated / version 1.8, the fractional total uncertainty of version 1.8 (with
its MCS-scale term) and of the calibrated result (with the calibration term), the calibration term in units of the
calibrated total, and the closure chi2 of both.

    python3 scripts/mcs_cal_compare.py  ->  report/planning/multipion/mcs_cal_compare.{md,json}
"""
import json, os, re
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, '..'))
CAL = '/data/uboone/processed/mcscal/'
REL = '/home/t2k/nowak/MicroBooNE/working_xsec_analyzer/report/data_release/cov/'     # version 1.8
BASE = '/data/uboone/processed/mcsmap_study/base/'                                    # version-1.8 extraction logs
DOC = os.path.abspath(os.path.join(REPO, '..', 'report', 'planning', 'multipion'))
TERMS = {'model': ('shrink', None), 'grid': ('coarse', 'fine'), 'production': ('old_production', 'new_production'),
         'beam': ('FHC', 'RHC')}


def vec(p):
    return np.array([float(a[1]) for a in (l.split() for l in open(p)) if len(a) == 2 and a[0] != 'numXbins'])


def cov(p):
    r = [l.split() for l in open(p)]; n = int(r[0][1]); m = np.zeros((n, n))
    for a in r[3:]:
        if len(a) == 3: m[int(a[0]), int(a[1])] = float(a[2])
    return m


def write(p, C):
    n = len(C)
    with open(p, 'w') as o:
        o.write(f'numXbins {n}\nnumYbins {n}\nxbin  ybin  z\n')
        for i in range(n):
            for j in range(n): o.write(f'{i}  {j}  {C[i, j]:.17e}\n')


def closure(log):
    if not os.path.exists(log): return None
    m = re.search(r'^truth: χ² = (\S+)/(\d+) bin', open(log).read(), re.M)
    return (float(m.group(1)), int(m.group(2))) if m else None


def main():
    tags = [os.path.basename(l.split()[0])[:-4] for l in open(os.path.join(REPO, 'slurm', 'mcscal_manifest.list')) if l.strip()]
    out, L = {}, []
    L += ['# MCS-calibrated results against version 1.8', '',
          'Generated by `scripts/mcs_cal_compare.py`. Calibrated: every simulated sample (overlay, dirt, detector variations, '
          'pseudo-data) with the MCS momentum of simulated exiting muon candidates mapped to the control-region data '
          '(`scripts/mcs_cal_derive.py`, `macros/mcs_cal_apply.C`), universes rebuilt, version-1.8 systematics. The '
          'calibration term is the sum of the model, grid, production and beam variations of the map.', '',
          '| Result | integral cal / v1.8 | cal / v1.8 per bin | total unc. v1.8 (with MCS scale) | total unc. calibrated (with calibration term) | calibration term / total | closure chi2 v1.8 | calibrated |',
          '|---|---|---|---|---|---|---|---|']
    for t in tags:
        n_ = CAL + 'nominal_out/' + t + '/'
        if not os.path.exists(n_ + 'unfolded_signal.txt'):
            L.append(f'| {t} | missing | | | | | | |'); continue
        x = vec(n_ + 'unfolded_signal.txt'); Ct = cov(n_ + 'cov_total.txt')
        xr = vec(REL + t + '/unfolded_signal.txt')
        Cr = cov(REL + t + '/cov_total_plusMCS.txt') if os.path.exists(REL + t + '/cov_total_plusMCS.txt') else cov(REL + t + '/cov_total.txt')
        Ci = np.linalg.pinv(Ct)
        C = np.zeros_like(Ct); terms = {}; missing = []
        for name, (a, b) in TERMS.items():
            va = CAL + f'var/{a}/{t}/unfolded_signal.txt'
            vb = CAL + f'var/{b}/{t}/unfolded_signal.txt' if b else None
            if not os.path.exists(va) or (vb and not os.path.exists(vb)): missing.append(name); continue
            if name == 'grid':
                ds = [vec(va) - x, vec(vb) - x]
                d = max(ds, key=lambda d: d @ Ci @ d)
            elif b:
                d = (vec(va) - vec(vb)) / 2
            else:
                d = vec(va) - x
            terms[name] = d.tolist(); C += np.outer(d, d)
        write(n_ + 'cov_MCScal.txt', C); write(n_ + 'cov_total_plusMCScal.txt', Ct + C)
        sr, sc = np.sqrt(np.diag(Cr)) / np.abs(xr), np.sqrt(np.diag(Ct + C)) / np.abs(x)
        q = np.sqrt(np.diag(C)) / np.sqrt(np.diag(Ct + C))
        c0, c1 = closure(BASE + t + '/run.log'), closure(n_ + 'run.log')
        out[t] = dict(ratio=(x / xr).tolist(), integral=float(x.sum() / xr.sum()), unc_v18=sr.tolist(), unc_cal=sc.tolist(),
                      cal_term=q.tolist(), terms=terms, missing=missing, closure_v18=c0, closure_cal=c1)
        f = lambda v, d=2: ' '.join(f'{y:.{d}f}' for y in v)
        L.append(f'| {t} | {x.sum() / xr.sum():.3f} | {f(x / xr, 3)} | {f(sr)} | {f(sc)} | {f(q)}{" (missing " + ",".join(missing) + ")" if missing else ""} | '
                 f'{"%.2f/%d" % c0 if c0 else "-"} | {"%.2f/%d" % c1 if c1 else "-"} |')
    L += ['', '## Calibration terms per result (shift / calibrated total uncertainty, per bin)', '',
          '| Result | ' + ' | '.join(TERMS) + ' |', '|---|' + '---|' * len(TERMS)]
    for t, r in out.items():
        Ct = cov(CAL + 'nominal_out/' + t + '/cov_total.txt'); s = np.sqrt(np.diag(Ct))
        L.append(f'| {t} | ' + ' | '.join(' '.join(f'{v:+.2f}' for v in np.array(r['terms'][k]) / s) if k in r['terms'] else '-'
                                          for k in TERMS) + ' |')
    json.dump(out, open(os.path.join(DOC, 'mcs_cal_compare.json'), 'w'), indent=1)
    open(os.path.join(DOC, 'mcs_cal_compare.md'), 'w').write('\n'.join(L) + '\n')
    print('\n'.join(L))


if __name__ == '__main__':
    main()
