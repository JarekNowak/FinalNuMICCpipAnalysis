"""cr_llr_spike.py -- the excess of beam-on tracks at the proton end of the LLR score (report/planning/multipion/
cr_mp2pi_check.md: long pool tracks with LLR score below -0.9), broken down by period, length, direction, containment
and wire plane, against the prediction (overlay, beam-off, dirt) in the opened control regions.

Input and scales as scripts/cr_mp2pi_check.py: the control-region skim of slurm/slurm_mp2pi_cr_skim.sbatch (or the
directory given as the first argument), every track of the classifier's pool (CC1mu2piBDTEvt_etrk_*), with the
per-plane LLRs of the ntuple (trk_llr_pid_{u,v,y}_v, trk_llr_pid_v) looked up through etrk_idx.

    python3 scripts/cr_llr_spike.py [skim_dir] [tag]  ->  report/planning/multipion/cr_llr_spike[_tag].{json,md}
"""
import json, os, sys
import numpy as np
import uproot
import awkward as ak

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, '..'))
from bkgfit import farsb as F
from bkgfit.dirt import dirt_perrun

SKIM = (sys.argv[1].rstrip('/') + '/') if len(sys.argv) > 1 else '/data/uboone/processed/mp2pi_cr_skim/'
TAG = ('_' + sys.argv[2]) if len(sys.argv) > 2 else ''
OUTDIR = os.path.abspath(os.path.join(HERE, '..', '..', 'report', 'planning', 'multipion'))
B = 'CC1mu2piBDTEvt'
ET = ['idx', 'len', 'llr', 'dirx', 'diry', 'dirz', 'contained', 'true_pdg', 'mom_mcs', 'mom_range_mu', 'dist']
PL = ['trk_llr_pid_u_v', 'trk_llr_pid_v_v', 'trk_llr_pid_y_v', 'trk_llr_pid_v']
LONG, SPIKE = 40., -0.9


def safe(w):
    return np.where(np.isfinite(w) & (w >= 0) & (w <= 30), w, 1.)


def tracks(path, scale, weighted):
    """flat per-track arrays of the pool tracks of one file, with the event weight"""
    t = uproot.open(path)['stv_tree']
    br = [f'{B}_etrk_{v}' for v in ET] + PL + \
         (['tuned_cv_weight', 'ppfx_cv_weight', 'normalisation_weight'] if weighted else [])
    out = {k: [] for k in ET + ['u', 'v', 'y', 'sum', 'w']}
    for a in t.iterate(br, step_size='200 MB', library='ak'):
        if len(a) == 0: continue
        w = safe(ak.to_numpy(a['tuned_cv_weight'] * a['ppfx_cv_weight'] * a['normalisation_weight'])) if weighted \
            else np.ones(len(a))
        idx = a[f'{B}_etrk_idx']
        for k in ET: out[k].append(ak.to_numpy(ak.flatten(a[f'{B}_etrk_{k}'])).astype(float))
        for k, b in zip(['u', 'v', 'y', 'sum'], PL):
            out[k].append(ak.to_numpy(ak.flatten(a[b][idx])).astype(float))
        out['w'].append(ak.to_numpy(ak.flatten(ak.broadcast_arrays(w * scale, idx)[0])))
    return {k: np.concatenate(v) if v else np.zeros(0) for k, v in out.items()}


def cat(xs):
    return {k: np.concatenate([x[k] for x in xs]) for k in xs[0]} if xs else {}


def ratio(d, p, dw2=None, pw2=None):
    r = d / p if p > 0 else float('nan')
    e = r * np.sqrt((1. / d if d > 0 else 0.) + (pw2 / p ** 2 if pw2 is not None and p > 0 else 0.)) if p > 0 else float('nan')
    return r, e


def main():
    mc, ext, data = F.samples()
    re = lambda path: SKIM + os.path.basename(path)
    dirts = dirt_perrun('comb', where=lambda run: SKIM)
    D, P, PERIOD = {}, {}, {}
    for ip, name in enumerate(F.PNAME):
        if not data[ip]: continue
        D[name] = cat([tracks(re(f), 1., False) for f in data[ip]])
        parts = [dict(tracks(re(f), s, True), src=None) for f, s in mc[ip]]
        for x in parts: x['src'] = np.zeros(len(x['w']))                                          # overlay
        e = [tracks(re(f), s, False) for f, s in ext[ip]]
        for x in e: x['src'] = np.ones(len(x['w']))                                               # beam-off
        dd = [tracks(f, s, True) for r, f, s in dirts if r == F.RUN[ip]]
        for x in dd: x['src'] = 2 * np.ones(len(x['w']))                                          # dirt
        P[name] = cat(parts + e + dd)
        PERIOD[name] = name
        print(f'== {name} done', flush=True)
    res = {}
    L = ['# Proton-end excess of the LLR score in the opened control regions', '',
         f'Generated by `scripts/cr_llr_spike.py` from `{SKIM}`. Pool tracks of the two-pion classifier '
         f'(`{B}_etrk_*`); "long" means length >= {LONG:.0f} cm, "spike" means LLR score < {SPIKE}. Data / prediction '
         '(overlay, beam-off, dirt), counts weighted.', '']

    def table(title, rows, sel_d, sel_p, key):
        L.extend([f'## {title}', '', '| | data | prediction | ratio | data share | prediction share |', '|---|---|---|---|---|---|'])
        out = {}
        nd_all = sum(sel_d(n).sum() for n in D); np_all = sum(P[n]['w'][sel_p(n)].sum() for n in P)
        for lab, fd, fp in rows:
            nd = sum((sel_d(n) & fd(D[n])).sum() for n in D)
            pw = [P[n]['w'][sel_p(n) & fp(P[n])] for n in P]
            npred = sum(x.sum() for x in pw); pw2 = sum((x ** 2).sum() for x in pw)
            r, e = ratio(nd, npred, pw2=pw2)
            out[lab] = dict(data=float(nd), pred=float(npred), ratio=r, err=e)
            L.append(f'| {lab} | {nd:.0f} | {npred:.1f} | {r:.2f} ± {e:.2f} | {nd / max(nd_all, 1):.3f} | '
                     f'{npred / max(np_all, 1e-9):.3f} |')
        L.append(''); res[key] = out

    long_d = lambda n: D[n]['len'] >= LONG
    long_p = lambda n: P[n]['len'] >= LONG
    spk_d = lambda n: long_d(n) & (D[n]['llr'] < SPIKE)
    spk_p = lambda n: long_p(n) & (P[n]['llr'] < SPIKE)

    # 1. LLR score of long tracks, all periods
    edges = [-1, -0.99, -0.95, -0.9, -0.8, -0.5, 0, 0.5, 1.01]
    table('LLR score of long tracks', [(f'{lo} to {hi}', (lambda lo, hi: lambda x: (x['llr'] >= lo) & (x['llr'] < hi))(lo, hi),
                                        (lambda lo, hi: lambda x: (x['llr'] >= lo) & (x['llr'] < hi))(lo, hi))
                                       for lo, hi in zip(edges[:-1], edges[1:])], long_d, long_p, 'llr_long')
    # 2. per period
    L.extend(['## Spike tracks per period', '', '| period | data | prediction | ratio | long tracks: data / prediction |', '|---|---|---|---|---|'])
    res['period'] = {}
    for n in D:
        nd = spk_d(n).sum(); w = P[n]['w'][spk_p(n)]; npred = w.sum(); r, e = ratio(nd, npred, pw2=(w ** 2).sum())
        rl = long_d(n).sum() / P[n]['w'][long_p(n)].sum()
        res['period'][n] = dict(data=float(nd), pred=float(npred), ratio=r, err=e, long_ratio=float(rl))
        L.append(f'| {n} | {nd:.0f} | {npred:.1f} | {r:.2f} ± {e:.2f} | {rl:.3f} |')
    L.append('')
    # 3. breakdowns of the spike tracks
    ax = lambda k, lo, hi: (lambda x: (np.abs(x[k]) >= lo) & (np.abs(x[k]) < hi))
    table('Spike tracks by |dir x| (drift)', [(f'{lo}-{hi}', ax('dirx', lo, hi), ax('dirx', lo, hi))
                                             for lo, hi in ((0, .3), (.3, .6), (.6, .85), (.85, 1.01))], spk_d, spk_p, 'dirx')
    table('Spike tracks by dir y', [(f'{lo} to {hi}', (lambda lo, hi: lambda x: (x['diry'] >= lo) & (x['diry'] < hi))(lo, hi),
                                     (lambda lo, hi: lambda x: (x['diry'] >= lo) & (x['diry'] < hi))(lo, hi))
                                    for lo, hi in ((-1.01, -0.5), (-0.5, 0), (0, 0.5), (0.5, 1.01))], spk_d, spk_p, 'diry')
    table('Spike tracks by dir z', [(f'{lo} to {hi}', (lambda lo, hi: lambda x: (x['dirz'] >= lo) & (x['dirz'] < hi))(lo, hi),
                                     (lambda lo, hi: lambda x: (x['dirz'] >= lo) & (x['dirz'] < hi))(lo, hi))
                                    for lo, hi in ((-1.01, -0.5), (-0.5, 0), (0, 0.5), (0.5, 1.01))], spk_d, spk_p, 'dirz')
    table('Spike tracks by length [cm]', [(f'{lo}-{hi}', (lambda lo, hi: lambda x: (x['len'] >= lo) & (x['len'] < hi))(lo, hi),
                                           (lambda lo, hi: lambda x: (x['len'] >= lo) & (x['len'] < hi))(lo, hi))
                                          for lo, hi in ((40, 60), (60, 100), (100, 200), (200, 1e9))], spk_d, spk_p, 'len')
    cont = {0: 'neither end contained', 1: 'start only', 2: 'end only', 3: 'both ends contained'}
    table('Spike tracks by containment', [(v, (lambda c: lambda x: x['contained'] == c)(c), (lambda c: lambda x: x['contained'] == c)(c))
                                          for c, v in cont.items()], spk_d, spk_p, 'contained')
    table('Spike tracks by vertex distance [cm]', [(f'{lo}-{hi}', (lambda lo, hi: lambda x: (x['dist'] >= lo) & (x['dist'] < hi))(lo, hi),
                                                    (lambda lo, hi: lambda x: (x['dist'] >= lo) & (x['dist'] < hi))(lo, hi))
                                                   for lo, hi in ((0, 1), (1, 4), (4, 10), (10, 1e9))], spk_d, spk_p, 'dist')
    # 4. which plane: per-plane LLR of the spike tracks (most negative plane; planes below -50)
    def plane_rows():
        rows = []
        for pl in ('u', 'v', 'y'):
            rows.append((f'{pl} LLR < -50', (lambda pl: lambda x: x[pl] < -50)(pl), (lambda pl: lambda x: x[pl] < -50)(pl)))
        rows.append(('all three planes < -50', lambda x: (x['u'] < -50) & (x['v'] < -50) & (x['y'] < -50),
                     lambda x: (x['u'] < -50) & (x['v'] < -50) & (x['y'] < -50)))
        rows.append(('only one plane < -50', lambda x: ((x['u'] < -50).astype(int) + (x['v'] < -50) + (x['y'] < -50)) == 1,
                     lambda x: ((x['u'] < -50).astype(int) + (x['v'] < -50) + (x['y'] < -50)) == 1))
        for pl in ('u', 'v', 'y'):
            rows.append((f'{pl} LLR exactly 0 (no plane information)', (lambda pl: lambda x: x[pl] == 0)(pl),
                         (lambda pl: lambda x: x[pl] == 0)(pl)))
        return rows
    table('Spike tracks by wire plane', plane_rows(), spk_d, spk_p, 'plane')
    # 5. composition of the predicted spike: source and true particle
    L.extend(['## Predicted spike tracks by source and true particle', '', '| | prediction | share |', '|---|---|---|'])
    tot = sum(P[n]['w'][spk_p(n)].sum() for n in P); comp = {}
    for lab, f in (('overlay, true proton', lambda x: (x['src'] == 0) & (np.abs(x['true_pdg']) == 2212)),
                   ('overlay, true muon', lambda x: (x['src'] == 0) & (np.abs(x['true_pdg']) == 13)),
                   ('overlay, true charged pion', lambda x: (x['src'] == 0) & (np.abs(x['true_pdg']) == 211)),
                   ('overlay, other simulated', lambda x: (x['src'] == 0) & (x['true_pdg'] != 0) &
                    ~np.isin(np.abs(x['true_pdg']), [13, 211, 2212])),
                   ('overlay, cosmic (no simulated match)', lambda x: (x['src'] == 0) & (x['true_pdg'] == 0)),
                   ('beam-off', lambda x: x['src'] == 1), ('dirt', lambda x: x['src'] == 2)):
        v = sum(P[n]['w'][spk_p(n) & f(P[n])].sum() for n in P); comp[lab] = float(v)
        L.append(f'| {lab} | {v:.1f} | {v / max(tot, 1e-9):.3f} |')
    res['composition'] = comp
    L.append('')
    # 6. momenta of the spike tracks: range (muon hypothesis) and MCS, means
    L.extend(['## Spike tracks: mean momenta [GeV/c]', '', '| | data | prediction |', '|---|---|---|'])
    for k in ('mom_range_mu', 'mom_mcs'):
        md = np.mean(np.concatenate([D[n][k][spk_d(n)] for n in D]))
        wp = np.concatenate([P[n]['w'][spk_p(n)] for n in P]); xp = np.concatenate([P[n][k][spk_p(n)] for n in P])
        L.append(f'| {k} | {md:.3f} | {np.average(xp, weights=wp):.3f} |')
    L.append('')
    json.dump(res, open(os.path.join(OUTDIR, f'cr_llr_spike{TAG}.json'), 'w'), indent=1, default=float)
    open(os.path.join(OUTDIR, f'cr_llr_spike{TAG}.md'), 'w').write('\n'.join(L) + '\n')
    print('\n'.join(L))


if __name__ == '__main__':
    main()
