"""mcs_map_compare.py -- tables of slurm/slurm_mcsmap_impact.sbatch: for every released result that uses the muon
momentum, the unfolded result with the MCS momenta of the pseudo-data mapped to the control-region data ("map") against
the release extraction ("base"), per bin: the ratio, the shift in units of the official version-1.8 uncertainty
(cov_total_plusMCS of the data release), and the released MCS term (cov_MCSscale) in the same units. "base" is checked
against the released unfolded values.

    python3 scripts/mcs_map_compare.py  ->  report/planning/multipion/mcs_map_impact.{md,json}
"""
import json, os
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, '..'))
OUT = '/data/uboone/processed/mcsmap_study/'
REL = '/home/t2k/nowak/MicroBooNE/working_xsec_analyzer/report/data_release/cov/'   # version 1.8 (release/v1.8)
DOC = os.path.abspath(os.path.join(REPO, '..', 'report', 'planning', 'multipion'))


def vec(p):
    r = [l.split() for l in open(p)][1:]
    return np.array([float(a[1]) for a in r if len(a) == 2])


def cov(p):
    r = [l.split() for l in open(p)]; n = int(r[0][1]); m = np.zeros((n, n))
    for a in r[3:]:
        if len(a) == 3: m[int(a[0]), int(a[1])] = float(a[2])
    return m


def main():
    tags = [l.split('|')[0] for l in open(os.path.join(REPO, 'slurm', 'mcsmap_products.list')) if l.strip()]
    res, L = {}, []
    L += ['# Impact of the MCS mis-modelling of exiting muons on the released results', '',
          'Generated by `scripts/mcs_map_compare.py` from `slurm/slurm_mcsmap_impact.sbatch`. The MCS-measured muon '
          'momenta of the release pseudo-data are mapped to the control-region data (`scripts/mcs_map_derive.py`: f(p)/p '
          '= 0.95 at 0.4, 0.87 at 0.8, 0.78 at 1.5, 0.73 at 2.0 GeV/c) and unfolded with the nominal response. Per bin: '
          'map / base, the shift (map - base) in units of the official version-1.8 uncertainty, and the released MCS term '
          'in the same units.', '',
          '| Result | base = v1.8 | integral map/base | map / base per bin | shift / sigma per bin | released MCS term / sigma |',
          '|---|---|---|---|---|---|']
    for t in tags:
        b, m = OUT + 'base/' + t + '/', OUT + 'map/' + t + '/'
        if not (os.path.exists(b + 'unfolded_signal.txt') and os.path.exists(m + 'unfolded_signal.txt')):
            L.append(f'| {t} | missing | | | | |'); continue
        xb, xm = vec(b + 'unfolded_signal.txt'), vec(m + 'unfolded_signal.txt')
        xr = vec(REL + t + '/unfolded_signal.txt')
        same = bool(np.allclose(xb, xr, rtol=1e-6, atol=0))
        sig = np.sqrt(np.diag(cov(REL + t + '/cov_total_plusMCS.txt')))
        mcs = np.sqrt(np.diag(cov(REL + t + '/cov_MCSscale.txt'))) if os.path.exists(REL + t + '/cov_MCSscale.txt') else np.zeros_like(sig)
        r = xm / xb; s = (xm - xb) / sig; q = mcs / sig
        res[t] = dict(base_is_release=same, integral_ratio=float(xm.sum() / xb.sum()), ratio=r.tolist(), shift_sigma=s.tolist(),
                      released_mcs_sigma=q.tolist(), base=xb.tolist(), map=xm.tolist())
        L.append(f'| {t} | {"yes" if same else "NO"} | {xm.sum() / xb.sum():.3f} | {" ".join(f"{x:.3f}" for x in r)} | '
                 f'{" ".join(f"{x:+.2f}" for x in s)} | {" ".join(f"{x:.2f}" for x in q)} |')
    if res:
        mx = max(res.items(), key=lambda kv: max(abs(np.array(kv[1]['shift_sigma']))))
        L += ['', f'Largest shift: {max(abs(np.array(mx[1]["shift_sigma"]))):.2f} sigma ({mx[0]}).']
    # reco level: selected pseudo-data events in the released p_mu bins, mapped against nominal (the selection is unchanged)
    import uproot
    E = [0, 0.3, 0.425, 0.575, 0.825, 1.25, 99.]
    L += ['', 'Reco level, inclusive pseudo-data in the released p_mu bins (selected events, mapped / nominal; the '
          'control-region data / prediction shape was 1.00 1.07 1.21 1.25 1.09 0.48):', '']
    for c in ('fhc', 'rhc'):
        hn, hm = np.zeros(6), np.zeros(6)
        for r in (1, 2, 3, 4, 5):
            fm = OUT + f'fakedata/xsec-ana-fakedata_{c}_run{r}.root'
            if not os.path.exists(fm): continue
            for p, h in (('/data/uboone/processed/' + os.path.basename(fm), hn), (fm, hm)):
                a = uproot.open(p)['stv_tree'].arrays(['CC1mu1piXp_Selected', 'CC1mu1piXp_candidate_muon_mom_reco'], library='np')
                h += np.histogram(a['CC1mu1piXp_candidate_muon_mom_reco'][a['CC1mu1piXp_Selected'].astype(bool)], E)[0]
        res[f'reco_{c}'] = dict(nominal=hn.tolist(), mapped=hm.tolist())
        L.append(f'- {c.upper()}: {int(hn.sum())} / {int(hm.sum())} events; ' + ' '.join(f'{x:.3f}' for x in hm / hn))
    json.dump(res, open(os.path.join(DOC, 'mcs_map_impact.json'), 'w'), indent=1)
    open(os.path.join(DOC, 'mcs_map_impact.md'), 'w').write('\n'.join(L) + '\n')
    print('\n'.join(L))


if __name__ == '__main__':
    main()
