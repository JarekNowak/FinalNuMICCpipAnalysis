"""cr_mp2pi_score_split.py -- the event score of the two-pion domain (regions 1-4) per opened control region of the
single-pion analysis, data / prediction in four coarse score bins, from the control-region skim (default: the one with
the MCS-calibrated classifier inputs). Separates the shape of the score within a region from the different
normalisations of the regions, which the summed shape test of scripts/cr_mp2pi_check.py mixes.

    python3 scripts/cr_mp2pi_score_split.py [skim_dir]  ->  report/planning/multipion/cr_mp2pi_score_split.md
"""
import os, sys
import numpy as np
import uproot

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, '..'))
from bkgfit import farsb as F
from bkgfit.dirt import dirt_perrun

SK = (sys.argv[1].rstrip('/') + '/') if len(sys.argv) > 1 else '/data/uboone/processed/mp2pi_cr_skim_mcscal/'
OUTDIR = os.path.abspath(os.path.join(HERE, '..', '..', 'report', 'planning', 'multipion'))
S, B = 'CC1mu1piXp', 'CC1mu2piBDTEvt'
CR = ['sb_cc0pi', 'sb_multipi', 'sb_pi0', 'sb_cosmic']
SC = np.array([0, 0.04, 0.2, 0.5, 0.92])
SRC = ('overlay', 'beam-off', 'dirt')


def safe(w):
    return np.where(np.isfinite(w) & (w >= 0) & (w <= 30), w, 1.)


def fill(path, scale, weighted, H, src):
    t = uproot.open(path)['stv_tree']
    br = [f'{S}_{c}' for c in CR] + [f'{B}_evt_region', f'{B}_evt_score'] + \
         (['tuned_cv_weight', 'ppfx_cv_weight', 'normalisation_weight'] if weighted else [])
    a = t.arrays(br, library='np')
    n = len(a[br[0]])
    w = safe(a['tuned_cv_weight'] * a['ppfx_cv_weight'] * a['normalisation_weight']) * scale if weighted else np.full(n, scale)
    dom = a[f'{B}_evt_region'] >= 1
    sc = np.clip(a[f'{B}_evt_score'], 0, SC[-1] - 1e-9)
    for c in CR:
        m = dom & a[f'{S}_{c}'].astype(bool)
        H.setdefault((c, src), np.zeros(len(SC) - 1))
        H[(c, src)] += np.histogram(sc[m], SC, weights=w[m])[0]


def main():
    mc, ext, data = F.samples()
    re = lambda p: SK + os.path.basename(p)
    dirts = dirt_perrun('comb', where=lambda run: SK)
    H = {}
    for ip, name in enumerate(F.PNAME):
        if not data[ip]: continue
        for f in data[ip]: fill(re(f), 1., False, H, 'data')
        for f, s in mc[ip]: fill(re(f), s, True, H, 'overlay')
        for f, s in ext[ip]: fill(re(f), s, False, H, 'beam-off')
        for r, f, s in dirts:
            if r == F.RUN[ip]: fill(f, s, True, H, 'dirt')
    bins = [f'{SC[i]:g}-{SC[i + 1]:g}' for i in range(len(SC) - 1)]
    L = ['# Event score of the two-pion domain per control region', '',
         f'Generated by `scripts/cr_mp2pi_score_split.py` from `{SK}`. Data / prediction (overlay, beam-off, dirt) per '
         'score bin; "within region" divides by the ratio of that region over the whole domain, "within domain" by the '
         'ratio of all regions together (the normalisation of the summed shape test).', '',
         '| control region | ' + ' | '.join(bins) + ' | region total | share of the lowest bin |',
         '|---|' + '---|' * (len(bins) + 2)]
    td, tp = np.zeros(len(bins)), np.zeros(len(bins))
    pred = {c: sum(H[(c, s)] for s in SRC) for c in CR}
    for c in CR: td += H[(c, 'data')]; tp += pred[c]
    for c in CR:
        d, p = H[(c, 'data')], pred[c]
        if p.sum() <= 0: continue
        rt = d.sum() / p.sum()
        cells = [f'{d[i]:.0f}/{p[i]:.1f} ({d[i] / p[i]:.2f}; within region {d[i] / p[i] / rt:.2f})' if p[i] > 0 else 'n/a'
                 for i in range(len(bins))]
        L.append(f'| {c} | ' + ' | '.join(cells) + f' | {rt:.3f} | {p[0] / tp[0]:.3f} |')
    rt = td.sum() / tp.sum()
    L.append('| all | ' + ' | '.join(f'{td[i]:.0f}/{tp[i]:.1f} ({td[i] / tp[i]:.2f}; within domain {td[i] / tp[i] / rt:.2f})'
                                     for i in range(len(bins))) + f' | {rt:.3f} | 1 |')
    open(os.path.join(OUTDIR, 'cr_mp2pi_score_split.md'), 'w').write('\n'.join(L) + '\n')
    print('\n'.join(L))


if __name__ == '__main__':
    main()
