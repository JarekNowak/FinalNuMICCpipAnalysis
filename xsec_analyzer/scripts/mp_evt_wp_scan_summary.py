"""mp_evt_wp_scan_summary.py -- working point of the two-pion event classifier on the constrained total: collects the
per-threshold tables of `scripts/mp_evt.py constraint --threshold T` (phase4_constraint<tag>[_<set>]_t<T>.md) into
one table: signal-region yield and purity, the unconstrained total, and the total and its terms with all sidebands.

    python3 scripts/mp_evt_wp_scan_summary.py [tag] [set]   (default llronly pid)  ->  report/planning/multipion/phase4_wp_scan_<tag>[_<set>].md
"""
import glob, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
D = os.path.abspath(os.path.join(HERE, '..', '..', 'report', 'planning', 'multipion'))
TAG = sys.argv[1] if len(sys.argv) > 1 else 'llronly'
SET = sys.argv[2] if len(sys.argv) > 2 else 'pid'
SUF = TAG + (f'_{SET}' if SET != 'pid' else '')


def cells(line):
    return [c.strip() for c in line.strip().strip('|').split('|')]


def main():
    rows = []
    for f in glob.glob(os.path.join(D, f'phase4_constraint_{SUF}_t*.md')):
        T = float(re.search(r'_t([\d.]+)\.md$', f).group(1))
        L = open(f).read().splitlines()
        sr = next(cells(l) for l in L if l.startswith('| SR |'))
        none = next(cells(l) for l in L if l.startswith('| none |'))
        allsb = next(cells(l) for l in L if l.startswith('| all sidebands |'))
        rows.append((T, sr, none, allsb))
    rows.sort()
    head = ['Total', 'Flux', 'Cross section', 'Reinteraction', 'Detector', 'POT, targets', 'Data statistics', 'MC statistics']
    out = [f'# Working point of the two-pion event classifier on the constrained total ({TAG}, {SET} set)', '',
           'Generated by `scripts/mp_evt_wp_scan_summary.py` from `scripts/mp_evt.py constraint --threshold T` (COMB, full '
           'exposure, the formalism of the ConstrainedCalculator). The adopted threshold is 0.92.', '',
           '| Score > | SR events | SR signal | Purity | Total, no constraint | ' + ' | '.join(f'{h}, all sidebands' for h in head) + ' |',
           '|---|---|---|---|---|' + '---|' * len(head)]
    for T, sr, none, allsb in rows:
        out.append(f'| {T:g} | {sr[1]} | {sr[2]} | {sr[3]} | {none[1]} | ' + ' | '.join(allsb[1:1 + len(head)]) + ' |')
    open(os.path.join(D, f'phase4_wp_scan_{SUF}.md'), 'w').write('\n'.join(out) + '\n')
    print('\n'.join(out))


if __name__ == '__main__':
    main()
