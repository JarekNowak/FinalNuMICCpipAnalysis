"""mp2pi_mcscal_migration.py -- why the two-pion pseudo-data closure moves with the MCS-calibrated classifier inputs
(scripts/mp2pi_mcscal_compare.py). The calibrated and uncalibrated pseudo-data are the same thrown events (same seeds,
same weights); only the classification of the simulated events changes. Per pseudo-data file of the throw plan
(/data/uboone/processed/mp2pi_mcscal/throw_plan.txt): the signal-region count of the pseudo-data before and after,
its expectation (overlays and dirt with the plan's scales and the CV weight; beam-off is the same in both and left
out), the expected signal, and the events that enter and leave the signal region. The pseudo-data counts of the
migrating events are Poisson draws made without regard to their classification, so the change of the pseudo-data
count differs from the change of its expectation by a Poisson amount with variance (entering + leaving).

    python3 scripts/mp2pi_mcscal_migration.py  ->  report/planning/multipion/mp2pi_mcscal_migration.md
"""
import os
import numpy as np
import uproot

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.abspath(os.path.join(HERE, '..', '..', 'report', 'planning', 'multipion', 'mp2pi_mcscal_migration.md'))
DIRS = {'u': '/data/uboone/processed/mp2pi', 'c': '/data/uboone/processed/mp2pi_mcscal'}
R, S = 'CC1mu2piBDT_evt_region', 'CC1mu2piBDT_MC_Signal'


def safe(w):
    return np.where(np.isfinite(w) & (w >= 0) & (w <= 30), w, 1.)


def plan():
    p, cur = {}, None
    for l in open(DIRS['c'] + '/throw_plan.txt'):
        f = l.split()
        if f[0] == 'OUT': cur = f[1]; p[cur] = []
        else: p[cur].append((os.path.basename(f[1]), float(f[2])))
    return p


def main():
    rows, tot = [], {}
    for out, ins in plan().items():
        pd = {v: (uproot.open(f'{d}/{out}')['stv_tree'][R].array(library='np') == 0).sum() for v, d in DIRS.items()}
        e = dict(pu=0., pc=0., su=0., sc=0., ein=0., eout=0.)
        for fn, sc in ins:
            a = {}
            for v, d in DIRS.items():
                t = uproot.open(f'{d}/{fn}')['stv_tree']
                a[v] = t.arrays([R, S, 'tuned_cv_weight', 'ppfx_cv_weight', 'normalisation_weight'], library='np')
            w = safe(a['u']['tuned_cv_weight'] * a['u']['ppfx_cv_weight'] * a['u']['normalisation_weight']) * sc
            for v in ('u', 'c'):
                m = a[v][R] == 0
                e['p' + v] += w[m].sum(); e['s' + v] += w[m & a[v][S].astype(bool)].sum()
            e['ein'] += w[(a['u'][R] != 0) & (a['c'][R] == 0)].sum(); e['eout'] += w[(a['u'][R] == 0) & (a['c'][R] != 0)].sum()
        mode = 'FHC' if '_fhc_' in out else 'RHC'
        rows.append((out, pd, e))
        for k, x in list(e.items()) + [('du', pd['u']), ('dc', pd['c'])]: tot[(mode, k)] = tot.get((mode, k), 0.) + x
    L = ['# Two-pion pseudo-data closure with the MCS-calibrated classifier inputs: migration of signal-region events', '',
         'Generated by `scripts/mp2pi_mcscal_migration.py`. Signal region (event score > 0.92); expectation = overlays and '
         'dirt with the scales of the throw plan (beam-off identical in both and left out). "Entering" and "leaving" are '
         'the expected counts of the events that the calibrated classification moves into or out of the signal region.', '',
         '| pseudo-data | signal-region count, uncal -> cal | expected -> | expected signal -> | entering | leaving |',
         '|---|---|---|---|---|---|']
    for out, pd, e in rows:
        L.append(f"| {out} | {pd['u']} -> {pd['c']} | {e['pu']:.1f} -> {e['pc']:.1f} | {e['su']:.1f} -> {e['sc']:.1f} | "
                 f"{e['ein']:.1f} | {e['eout']:.1f} |")
    L += ['', '| mode | pseudo-data change | expected change | Poisson spread | pull | (pseudo-data - expected) / signal | '
          'expected signal | expected total |', '|---|---|---|---|---|---|---|---|']
    for m in ('FHC', 'RHC'):
        t = {k: tot[(m, k)] for k in ('du', 'dc', 'pu', 'pc', 'su', 'sc', 'ein', 'eout')}
        dpd, dex, sd = t['dc'] - t['du'], t['pc'] - t['pu'], np.sqrt(t['ein'] + t['eout'])
        L.append(f"| {m} | {dpd:+.0f} | {dex:+.1f} | {sd:.1f} | {(dpd - dex) / sd:+.1f} | "
                 f"{(t['du'] - t['pu']) / t['su']:+.3f} -> {(t['dc'] - t['pc']) / t['sc']:+.3f} | "
                 f"{t['su']:.1f} -> {t['sc']:.1f} ({t['sc'] / t['su'] - 1:+.1%}) | {t['pu']:.1f} -> {t['pc']:.1f} ({t['pc'] / t['pu'] - 1:+.1%}) |")
    open(OUT, 'w').write('\n'.join(L) + '\n')
    print('\n'.join(L))


if __name__ == '__main__':
    main()
