"""mp2pi_ens_summary.py -- pseudo-experiment ensembles of the two-pion one-bin total (slurm/slurm_mp2pi_ens.sbatch), per
ensemble (nominal; alt545: GENIE multisim universe 545; altdelta: the Delta->N pi angular unisim), configuration and
mode (without and with the sideband constraint). Per member: the extracted value and its truth from the closure sidecar
(h_unfolded_nuwro, h_fakedata_truth; h_genie_tune is the expected truth of the nominal model), and the fractional data
statistics and total uncertainty of the SYSTDUMP.

Nominal ensemble: offset of the mean from the expected truth, the spread of the members against the quoted data
statistics, the pulls (x - x_expected) / sigma_stat (mean, width) and the coverage of the 68% and 95% statistical
intervals (with the binomial uncertainty). Alternative models: the mean of extracted over member truth, and its bias in
units of the total uncertainty.

    python3 scripts/mp2pi_ens_summary.py  ->  report/planning/multipion/mp2pi_ensembles.{json,md}
"""
import glob, json, os, re
import numpy as np
import uproot

HERE = os.path.dirname(os.path.abspath(__file__))
OUTDIR = os.path.abspath(os.path.join(HERE, '..', '..', 'report', 'planning', 'multipion'))
E = '/data/uboone/processed/mp2pi_mcscal/ens/'
CFGS = {'fhc5': 'FHC', 'rhcfull': 'RHC', 'comb': 'COMB'}
MODES = {'': 'none', '_constr': 'sidebands'}


def member(d, cfg, mode):
    log, side = f'{d}/{cfg}{mode}.log', f'{d}/closure_hists_xsec_{cfg}{mode}.root'
    if not (os.path.exists(log) and os.path.exists(side)): return None
    t = open(log).read()
    v = {k: float(x) for k, x in re.findall(r'^\[SYSTDUMP\] (\S+) ([-\d.e+]+)$', t, re.M)}
    if 'sigma_int' not in v: return None
    f = uproot.open(side)
    return dict(x=float(f['h_unfolded_nuwro'].values().sum()), truth=float(f['h_fakedata_truth'].values().sum()),
                expected=float(f['h_genie_tune'].values().sum()), stat=v['DataStats'] / 100., total=v['total'] / 100.)


def main():
    res = {}
    L = ['# Pseudo-experiment ensembles of the two-pion one-bin total', '',
         'Generated by `scripts/mp2pi_ens_summary.py` from `slurm/slurm_mp2pi_ens.sbatch` (MCS-calibrated classifier inputs; '
         'members thrown from the sources of `macros/mp2pi_ens_source.C`, extracted with the nominal response).', '']
    for ens in ('nominal', 'alt545', 'altdelta'):
        dirs = sorted(glob.glob(f'{E}{ens}/m[0-9][0-9][0-9]'))
        if not dirs: continue
        if ens == 'nominal':
            L += [f'## Nominal ({len(dirs)} members)', '',
                  '| configuration | constraint | members | mean offset | spread | quoted data stat. | pull mean | pull width | '
                  '68% coverage | 95% coverage | mean extracted / member truth |', '|---|---|---|---|---|---|---|---|---|---|---|']
        else:
            L += [f'## Alternative model {ens} ({len(dirs)} members)', '',
                  '| configuration | constraint | members | extracted / truth (mean) | bias / total uncertainty | spread |',
                  '|---|---|---|---|---|---|']
        for cfg, cn in CFGS.items():
            for mode, mn in MODES.items():
                M = [m for m in (member(d, cfg, mode) for d in dirs) if m]
                if len(M) < 5: continue
                x = np.array([m['x'] for m in M]); tr = np.array([m['truth'] for m in M])
                ex = np.array([m['expected'] for m in M]); st = np.array([m['stat'] for m in M]); tot = np.array([m['total'] for m in M])
                key = f'{ens} {cn} {mn}'
                if ens == 'nominal':
                    rel = x / ex - 1.; pull = (x - ex) / (st * x)
                    c68 = np.mean(np.abs(pull) < 1.); c95 = np.mean(np.abs(pull) < 1.96); n = len(M)
                    r = dict(n=n, offset=float(rel.mean()), offset_err=float(rel.std(ddof=1) / np.sqrt(n)), spread=float(rel.std(ddof=1)),
                             quoted_stat=float(st.mean()), pull_mean=float(pull.mean()), pull_width=float(pull.std(ddof=1)),
                             cov68=float(c68), cov95=float(c95), closure=float(np.mean(x / tr)))
                    b = lambda p: np.sqrt(p * (1 - p) / n)
                    L.append(f"| {cn} | {mn} | {n} | {100 * r['offset']:+.1f} +- {100 * r['offset_err']:.1f}% | {100 * r['spread']:.1f}% | "
                             f"{100 * r['quoted_stat']:.1f}% | {r['pull_mean']:+.2f} | {r['pull_width']:.2f} | "
                             f"{100 * c68:.0f} +- {100 * b(0.68):.0f}% | {100 * c95:.0f} +- {100 * b(0.95):.0f}% | {r['closure']:.3f} |")
                else:
                    ratio = x / tr
                    r = dict(n=len(M), ratio=float(ratio.mean()), ratio_err=float(ratio.std(ddof=1) / np.sqrt(len(M))),
                             bias_sigma=float((ratio.mean() - 1.) / tot.mean()), spread=float(ratio.std(ddof=1)))
                    L.append(f"| {cn} | {mn} | {r['n']} | {r['ratio']:.3f} +- {r['ratio_err']:.3f} | {r['bias_sigma']:+.2f} | "
                             f"{100 * r['spread']:.1f}% |")
                res[key] = r
        L.append('')
    json.dump(res, open(os.path.join(OUTDIR, 'mp2pi_ensembles.json'), 'w'), indent=1)
    open(os.path.join(OUTDIR, 'mp2pi_ensembles.md'), 'w').write('\n'.join(L) + '\n')
    print('\n'.join(L))


if __name__ == '__main__':
    main()
