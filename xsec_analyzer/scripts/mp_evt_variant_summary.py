"""mp_evt_variant_summary.py -- the two-pion selection variants of the purity study on one page: particle classifier
(calorimetric or LLR-and-geometry, MCS-calibrated inputs) x event-classifier feature set (pid, shr1, shr), each with
its test-period AUC (phase2_event_<tag>.md), its best threshold on the constrained total and its values at the
adopted threshold 0.92 (phase4_wp_scan_<tag>[_<set>].md, scripts/mp_evt_wp_scan_summary.py), against the adopted
selection (LLR-and-geometry, pid set, uncalibrated inputs; phase4_wp_scan_llronly.md).

    python3 scripts/mp_evt_variant_summary.py  ->  report/planning/multipion/phase4_selection_variants.md
"""
import os, re

HERE = os.path.dirname(os.path.abspath(__file__))
D = os.path.abspath(os.path.join(HERE, '..', '..', 'report', 'planning', 'multipion'))
VARIANTS = [('llronly', 'pid', 'adopted: LLR-and-geometry, uncalibrated inputs'),
            ('llronly_mcscal', 'pid', 'LLR-and-geometry'), ('llronly_mcscal', 'shr1', 'LLR-and-geometry'),
            ('llronly_mcscal', 'shr', 'LLR-and-geometry'), ('mcscal', 'pid', 'calorimetric'),
            ('mcscal', 'shr1', 'calorimetric'), ('mcscal', 'shr', 'calorimetric')]
SETS = {'pid': 'existing (33)', 'shr1': 'leading shower (37)', 'shr': 'all shower (44)'}


def cells(line):
    return [c.strip() for c in line.strip().strip('|').split('|')]


def scan(tag, s):
    f = os.path.join(D, f'phase4_wp_scan_{tag}' + (f'_{s}' if s != 'pid' else '') + '.md')
    rows = [cells(l) for l in open(f) if re.match(r'^\| 0\.\d', l)]
    return [dict(T=float(r[0]), events=r[1], signal=r[2], purity=r[3], none=r[4], total=r[5], det=r[9], data=r[11])
            for r in rows]


def auc(tag, s):
    f = os.path.join(D, f'phase2_event_{tag}.md')
    for l in open(f):
        m = re.match(rf'^\| {s} \((\d+) features\) \| \d+ \| [\d.]+ \| ([\d.]+) \|', l)
        if m: return m.group(2)
    return 'n/a'


def main():
    L = ['# Two-pion selection variants: purity study (2026-10-16)', '',
         'Generated by `scripts/mp_evt_variant_summary.py`. Constrained total = the one-bin combined total with all four '
         'sidebands (formalism of the ConstrainedCalculator, `scripts/mp_evt.py constraint`), scanned at 0.85, 0.88, 0.90, '
         '0.92, 0.94, 0.95 and 0.96. AUC on the test periods (FHC Run 5, RHC Run 3). The detector term moves by 3-6 '
         'points between neighbouring thresholds of one variant, which bounds what the comparison resolves.', '',
         '| particle classifier | feature set | AUC | best threshold | purity | constrained total | detector | data stat. '
         '| at 0.92: purity | constrained total |', '|---|---|---|---|---|---|---|---|---|---|']
    for tag, s, name in VARIANTS:
        r = scan(tag, s)
        b = min(r, key=lambda x: float(x['total'].rstrip('%')))
        a = next(x for x in r if abs(x['T'] - 0.92) < 1e-9)
        L.append(f"| {name} | {SETS[s]} | {auc(tag, s)} | {b['T']:g} | {b['purity']} | {b['total']} | {b['det']} | "
                 f"{b['data']} | {a['purity']} | {a['total']} |")
    L += ['', 'Decision (2026-10-16): the adopted selection is kept; no variant lowers the constrained total beyond the '
          'scatter of the detector term.']
    open(os.path.join(D, 'phase4_selection_variants.md'), 'w').write('\n'.join(L) + '\n')
    print('\n'.join(L))


if __name__ == '__main__':
    main()
