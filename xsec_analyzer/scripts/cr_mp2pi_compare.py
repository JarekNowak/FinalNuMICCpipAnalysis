"""cr_mp2pi_compare.py -- the data check of the two-pion selection in the opened control regions
(scripts/cr_mp2pi_check.py) with the uncalibrated simulation against the simulation with the MCS-calibrated classifier
inputs (CC1MU1PIXP_MP_MCS_MAP, skim /data/uboone/processed/mp2pi_cr_skim_mcscal). Beam-on and beam-off are the same.

    python3 scripts/cr_mp2pi_compare.py  ->  report/planning/multipion/cr_mp2pi_mcscal_compare.md
"""
import json, os
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
D = os.path.abspath(os.path.join(HERE, '..', '..', 'report', 'planning', 'multipion'))
KEYS = ['event | score', 'event | L2_minus_L1', 'event | L2', 'event | sum_P_pi', 'event | n_P_pi_gt_0p5',
        'event | pool_size', 'event | topological_score', 'track | pid_mu', 'track | pid_pi', 'track | pid_p',
        'track | pid_other', 'track | llr', 'track | mom_mcs', 'track | mom_range_mu', 'track | len']
SHAPES = ['event | score', 'track | mom_mcs', 'track | pid_mu', 'track | pid_pi']


def main():
    a = json.load(open(os.path.join(D, 'cr_mp2pi_check.json')))
    b = json.load(open(os.path.join(D, 'cr_mp2pi_check_mcscal.json')))
    periods = [p for p in a if p != 'all']
    L = ['# Two-pion data check: uncalibrated simulation against the MCS-calibrated classifier inputs', '',
         'Generated by `scripts/cr_mp2pi_compare.py` from `cr_mp2pi_check.json` and `cr_mp2pi_check_mcscal.json`. '
         'The simulated samples of the control-region skim were processed again with the v1.9 MCS map applied to the '
         'classifier inputs of simulated exiting tracks; beam-on and beam-off data are unchanged. Shape chi2/ndf with '
         'the normalisation removed, all periods, and per period.', '',
         '| quantity | uncalibrated | calibrated | ' + ' | '.join(f'{p}: uncal / cal' for p in periods) + ' |',
         '|---|---|---|' + '---|' * len(periods)]
    for k in KEYS:
        x, y = a['all'][k], b['all'][k]
        cells = [f"{a[p][k]['chi2']:.0f} / {b[p][k]['chi2']:.0f}" if k in a[p] and k in b[p] else 'n/a' for p in periods]
        L.append(f"| {k} | {x['chi2']:.1f}/{x['ndf']} | {y['chi2']:.1f}/{y['ndf']} | " + ' | '.join(cells) + ' |')
    L += ['', '## Shapes, all periods: data over prediction per bin, each normalised to one', '']
    for k in SHAPES:
        L.append(f'**{k}**')
        L.append('')
        for lab, J in (('uncalibrated', a), ('calibrated', b)):
            d, p = np.array(J['all'][k]['data_hist']), np.array(J['all'][k]['pred_hist'])
            r = (d / d.sum()) / (p / p.sum())
            L.append(f'- {lab}: ' + ' '.join(f'{v:.2f}' for v in r))
        L.append('')
    L += ['## Two-pion sideband populations, all control regions: data / prediction', '',
          '| region | uncalibrated | calibrated |', '|---|---|---|']
    names = {1: 'three-pion-like', 2: 'proton-like', 3: 'score 0.5-0.92', 4: 'score < 0.5'}
    for r, n in names.items():
        k = f'events | all | region {r}'
        x, y = a['all'][k], b['all'][k]
        L.append(f"| {n} | {x['data']:.0f} / {x['pred']:.1f} ({x['ratio']:.3f}) | {y['data']:.0f} / {y['pred']:.1f} ({y['ratio']:.3f}) |")
    open(os.path.join(D, 'cr_mp2pi_mcscal_compare.md'), 'w').write('\n'.join(L) + '\n')
    print('\n'.join(L))


if __name__ == '__main__':
    main()
