"""mcs_cal_2d_screen.py -- binning of theta_p x delta p_T (proton-tagged, combined only) on the MCS-calibrated simulation.

With the calibrated muon momentum the third cell of the released binning (theta_p < 0.8 rad, delta p_T >= 0.3 GeV/c)
has a migration diagonal of 0.488 in the combined configuration, below the 0.50 criterion. Every 2 x 2 binning with
the theta_p edge in 0.60-1.20 rad and the delta p_T edge in 0.200-0.450 GeV/c is evaluated on the calibrated
proton-tagged simulation at data exposure: the column-normalised diagonal of each cell (selected signal) in FHC, RHC
and combined, and the selected signal per true cell. Rule: admissible when every combined diagonal is at least 0.50 and
every true cell holds at least 50 selected signal events (combined); the admissible binning closest to the released
edges (relative distance) is chosen, ties going to the larger smallest diagonal. The released binning is evaluated
first as a check against the unfolder's diagonal (0.693 0.647 0.488 0.690).

    python3 scripts/mcs_cal_2d_screen.py  ->  report/planning/multipion/mcs_cal_2d_screen.{md,json}
"""
import json, os
import numpy as np
import uproot

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, '..'))
DOC = os.path.abspath(os.path.join(REPO, '..', 'report', 'planning', 'multipion'))
S = 'CC1mu1pi1p_'
TH = np.round(np.arange(0.60, 1.2001, 0.05), 3)
DP = np.round(np.arange(0.200, 0.4501, 0.025), 3)
REL = (0.8, 0.3)


def safe(w):
    return np.where(np.isfinite(w) & (w >= 0) & (w <= 30), w, 1.)


def files(cfg):
    """numuMC and dirtMC files of the calibrated list with their data-exposure scale (per-run POT / distinct MC POT)"""
    rows = [l.split() for l in open(os.path.join(REPO, f'configs/mcscal/file_properties_numi_{cfg}_w.txt'))
            if l.strip() and not l.lstrip().startswith('#')]
    dpot = {r[1]: float(r[4]) for r in rows if len(r) >= 5 and r[2] == 'onBNB'}
    out = {}
    for kind in ('numuMC', 'dirtMC'):
        mc = [(r[0], r[1]) for r in rows if len(r) >= 3 and r[2] == kind]
        pot = {p: float(uproot.open(p)['summed_pot'].member('fVal')) for p, _ in mc}
        for p, run in mc:
            tot = sum(sorted(set(pot[q] for q, rr in mc if rr == run)))
            out[p] = dpot[run] / tot
    return out


def load(cfg):
    br = [S + b for b in ('Selected', 'MC_Signal', 'deltaPt_true', 'deltaPt_reco', 'proton_costh_true', 'proton_costh_reco')] + \
         ['tuned_cv_weight', 'ppfx_cv_weight', 'normalisation_weight']
    acc = []
    for p, sc in files(cfg).items():
        for a in uproot.open(p)['stv_tree'].iterate(br, step_size='400 MB', library='np'):
            m = a[S + 'Selected'].astype(bool) & a[S + 'MC_Signal'].astype(bool)
            w = safe(a['tuned_cv_weight'] * a['ppfx_cv_weight'] * a['normalisation_weight'])[m] * sc
            acc.append(np.stack([np.arccos(np.clip(a[S + 'proton_costh_true'][m], -1, 1)), a[S + 'deltaPt_true'][m],
                                 np.arccos(np.clip(a[S + 'proton_costh_reco'][m], -1, 1)), a[S + 'deltaPt_reco'][m], w]))
        print(cfg, os.path.basename(p), flush=True)
    return np.concatenate(acc, axis=1)


def cells(x, th, dp):
    """cell index in the released order: (dpT low, theta low), (dpT low, theta high), (dpT high, theta low), (dpT high, theta high)"""
    return 2 * (x[1] >= dp) + (x[0] >= th)


def evaluate(X, th, dp):
    t = cells(X[[0, 1]], th, dp); r = cells(X[[2, 3]], th, dp); w = X[4]
    d = np.array([w[(t == c) & (r == c)].sum() / max(w[t == c].sum(), 1e-12) for c in range(4)])
    n = np.array([w[t == c].sum() for c in range(4)])
    return d, n


def main():
    data = {c: load(c) for c in ('fhc5', 'rhcfull')}
    data['comb'] = np.concatenate([data['fhc5'], data['rhcfull']], axis=1)
    res = []
    for th in TH:
        for dp in DP:
            r = {c: evaluate(X, th, dp) for c, X in data.items()}
            res.append(dict(theta=float(th), dpt=float(dp), diag={c: v[0].round(4).tolist() for c, v in r.items()},
                            n={c: v[1].round(1).tolist() for c, v in r.items()},
                            dist=float(abs(th - REL[0]) / REL[0] + abs(dp - REL[1]) / REL[1])))
    rel = next(r for r in res if abs(r['theta'] - REL[0]) < 1e-6 and abs(r['dpt'] - REL[1]) < 1e-6)
    adm = [r for r in res if min(r['diag']['comb']) >= 0.50 and min(r['n']['comb']) >= 50]
    best = min(adm, key=lambda r: (round(r['dist'], 6), -min(r['diag']['comb']))) if adm else None
    json.dump(dict(released=rel, chosen=best, all=res), open(os.path.join(DOC, 'mcs_cal_2d_screen.json'), 'w'), indent=1)
    f = lambda v, d=3: ' '.join(f'{x:.{d}f}' for x in v)
    L = ['# theta_p x delta p_T binning on the MCS-calibrated simulation', '',
         'Generated by `scripts/mcs_cal_2d_screen.py`. Cells in the released order (delta p_T low/theta_p low, delta p_T '
         'low/theta_p high, delta p_T high/theta_p low, delta p_T high/theta_p high). Rule: every combined diagonal >= 0.50 '
         'and every true cell >= 50 selected signal events (combined, data exposure); the admissible binning closest to the '
         'released edges, ties to the larger smallest diagonal.', '',
         f'Released (theta_p 0.8 rad, delta p_T 0.3 GeV/c): combined diagonals {f(rel["diag"]["comb"])} (unfolder 0.693 0.647 0.488 0.690), '
         f'FHC {f(rel["diag"]["fhc5"])}, RHC {f(rel["diag"]["rhcfull"])}; combined signal per cell {f(rel["n"]["comb"], 0)}.', '',
         f'Admissible binnings: {len(adm)} of {len(res)}.', '']
    if best:
        L += [f'Chosen: theta_p edge {best["theta"]:.2f} rad, delta p_T edge {best["dpt"]:.3f} GeV/c; combined diagonals '
              f'{f(best["diag"]["comb"])}, FHC {f(best["diag"]["fhc5"])}, RHC {f(best["diag"]["rhcfull"])}; combined signal '
              f'per cell {f(best["n"]["comb"], 0)}.', '']
    L += ['## Smallest combined diagonal (rows theta_p edge [rad], columns delta p_T edge [GeV/c])', '',
          '| theta_p | ' + ' | '.join(f'{d:.3f}' for d in DP) + ' |', '|---|' + '---|' * len(DP)]
    for th in TH:
        L.append(f'| {th:.2f} | ' + ' | '.join(f'{min(r["diag"]["comb"]):.3f}' + ('*' if r in adm else '')
                                                 for r in res if abs(r['theta'] - th) < 1e-6) + ' |')
    L += ['', '* admissible.']
    open(os.path.join(DOC, 'mcs_cal_2d_screen.md'), 'w').write('\n'.join(L) + '\n')
    print('\n'.join(L))


if __name__ == '__main__':
    main()
