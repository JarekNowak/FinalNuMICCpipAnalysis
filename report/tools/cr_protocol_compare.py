"""cr_protocol_compare.py -- the frozen control-region protocol (macros/sb_protocol_data.C, sb_protocol.C) with the
simulation of version 1.7 against the MCS-calibrated simulation of version 1.9 (SB_MC_DIR=/data/uboone/processed/sb_mcscal/:
overlays, dirt and detector variations with the calibrated MCS momentum of exiting muons; beam-off and beam-on data
unchanged). The calibration was derived from these control regions, all regions and periods together, so on the
beam-on data this is a closure test per region and distribution, not an independent validation.

    python3 report/tools/cr_protocol_compare.py  ->  report/results/cr_protocol_mcscal.md
"""
import os, re

R = '/home/t2k/nowak/MicroBooNE/working_xsec_analyzer/'
RUNS = [('beam-on data', R + 'logs/crbraggfix/protocol_data.log', R + 'logs/v19/protocol_data_mcscal.log'),
        ('pseudo-data', R + 'logs/crbraggfix/protocol_pseudo.log', R + 'logs/v19/protocol_pseudo_mcscal.log')]


def parse(path):
    t = open(path).read()
    pulls = {(m, r): (float(a), float(b)) for m, r, a, b in
             re.findall(r'^(fhc|rhc)\s+(\S+)\s+[\d.]+\s+[\d.]+\s+(?:[\d.]+%)?\s*[\d.]+% \|\s+(\S+)\s+(\S+)', t, re.M)}
    shape = {(m, d): (float(c), int(n), float(p)) for m, d, c, n, p in
             re.findall(r'^(fhc|rhc)\s+(\S+_\S+)\s+\d+\s+([\d.]+)/(\d+)\s+([\d.]+)', t, re.M)}
    g = re.search(r'GLOBAL normalisation chi2 = ([\d.]+) / 8 dof, p = ([\d.]+)', t)
    return pulls, shape, (float(g.group(1)), float(g.group(2))) if g else None


def main():
    L = ['# Frozen control-region protocol: version-1.7 simulation against the MCS-calibrated simulation (version 1.9)', '',
         'Generated by `report/tools/cr_protocol_compare.py` from `logs/crbraggfix/protocol_*.log` and '
         '`logs/v19/protocol_*_mcscal.log`. The calibration of the MCS momentum of exiting muons was derived from these '
         'control regions (all regions and periods together): on the beam-on data the comparison is a closure test per '
         'region and distribution, not an independent validation. Region totals do not depend on the muon momentum.', '']
    for lab, a, b in RUNS:
        if not (os.path.exists(a) and os.path.exists(b)): L.append(f'{lab}: missing input'); continue
        pa, sa, ga = parse(a); pb, sb, gb = parse(b)
        L += [f'## {lab}', '', f'Global normalisation chi2: {ga[0]:.2f}/8 (p = {ga[1]:.3f}) -> {gb[0]:.2f}/8 (p = {gb[1]:.3f}).', '',
              '| mode | distribution | v1.7 chi2/ndf | p | calibrated chi2/ndf | p |', '|---|---|---|---|---|---|']
        for k in sorted(sa):
            x, y = sa[k], sb.get(k)
            flag = lambda p: f'**{p:.3f}**' if p < 0.05 else f'{p:.3f}'
            L.append(f'| {k[0]} | {k[1]} | {x[0]:.2f}/{x[1]} | {flag(x[2])} | ' + (f'{y[0]:.2f}/{y[1]} | {flag(y[2])} |' if y else '- | - |'))
        for lab2, sel in (('p_mu', lambda k: k[1].endswith('_pmu')), ('other', lambda k: not k[1].endswith('_pmu'))):
            ks = [k for k in sa if sel(k)]
            L.append(f'| sum | {lab2} | {sum(sa[k][0] for k in ks):.2f}/{sum(sa[k][1] for k in ks)} | | '
                     f'{sum(sb[k][0] for k in ks if k in sb):.2f}/{sum(sb[k][1] for k in ks if k in sb)} | |')
        if lab == 'pseudo-data':
            L += ['', 'The fake-data events of the two runs differ only in p_mu. The other pseudo-data shapes move because the '
                  'beam-off and dirt Poisson draws come from one random sequence (seed 20260903) and the calibrated dirt p_mu '
                  'bins change how much of it each draw consumes.']
        L += ['', '| mode | region | pull (full) v1.7 | calibrated | pull (st+det) v1.7 | calibrated |', '|---|---|---|---|---|---|']
        for k in sorted(pa):
            x, y = pa[k], pb.get(k, (float('nan'),) * 2)
            L.append(f'| {k[0]} | {k[1]} | {x[0]:+.2f} | {y[0]:+.2f} | {x[1]:+.2f} | {y[1]:+.2f} |')
        L.append('')
    out = R + 'report/results/cr_protocol_mcscal.md'
    open(out, 'w').write('\n'.join(L) + '\n'); print('\n'.join(L))


if __name__ == '__main__':
    main()
